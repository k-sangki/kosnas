/** 한 지표의 가장 최근 결과와 다음 발표 */
export function indicatorReleases(id: string, now = Date.now()) {
  const list = releases(BASE.rows ?? []).filter((r) => r.group === id);
  return {
    last: [...list].reverse().find((r) => r.out) ?? null,
    next: list.find((r) => !r.out && r.at > now - 3 * 3600_000) ?? null,
  };
}

export interface EarnLast {
  date: string;
  a: number;
  f: number | null;
  v: Verdict | null;
}

/** 한 기업의 가장 최근 실적과 다음 발표(나스닥 달력 → 없으면 야후) */
export function companyEarnings(sym: string, today = new Date(Date.now() - 5 * 3600_000).toISOString().slice(0, 10)) {
  const prof = COMP.profiles?.[sym];
  const cal = (BASE.earnings ?? []).filter((e) => e.symbol === sym).sort((a, b) => (a.date < b.date ? -1 : 1));
  const done = [...cal].reverse().find((e) => e.a != null);
  const pl = prof?.last;
  const last: EarnLast | null =
    done && (!pl || done.date >= pl.date)
      ? { date: done.date, a: done.a!, f: done.f, v: epsVerdict(done) }
      : pl && pl.a != null
        ? { date: pl.date, a: pl.a, f: pl.f, v: epsVerdict({ a: pl.a, f: pl.f } as Earning) }
        : null;
  const upcoming = cal.find((e) => e.a == null && e.date >= today);
  const next = upcoming
    ? { date: upcoming.date, f: upcoming.f, when: upcoming.when, estimate: false }
    : prof?.next && prof.next.date >= today
      ? { date: prof.next.date, f: prof.next.f, when: "", estimate: !!prof.next.estimate }
      : null;
  return { last, next, ly: upcoming?.ly ?? null };
}

