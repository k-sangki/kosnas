def sector_of(code: str, ksic: str | None) -> str:
    if code in OVERRIDES:
        return OVERRIDES[code]
    if not ksic:
        return "etc"
    for n in range(len(ksic), 1, -1):
        hit = KSIC_RULES.get(ksic[:n])
        if hit:
            return hit
    return "etc"
